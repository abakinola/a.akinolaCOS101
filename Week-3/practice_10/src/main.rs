fn main() {
    //addition
    let sum = 5550 + 7310;    
    println!("The sum of 5550 and 7310 = {}",sum);

    //subtraction
    let difference:f32 = 95.5 - 4.3;  //u32 was changed to f32                     
    println!("The difference of 95.5 and 4.3 = {}",difference);

    //multiplication
    let product:i32 = 4 * 30;         //f32 was changed to i32
    println!("The multiple of 4 and 30 = {}",product);

    //division
    let quotient = 56.7 / 32.2;
    println!("The division of 56.7 and 32.2 = {}", quotient);

    //remainder
    let remainder = 43 % 5;
    println!("The remainder if 43 and 5 = {}",remainder);
}
